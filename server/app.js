import express from 'express';
import path from 'path';
import { fileURLToPath } from 'url';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import morgan from 'morgan';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import foodRoutes from './routes/foods.js';
import orderRoutes from './routes/orders.js';
import adminRoutes from './routes/admin.js';
import couponRoutes from './routes/coupons.js';
import reviewRoutes from './routes/reviews.js';
import { clientCors } from './config/cors.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const app = express();
app.use(helmet({ crossOriginResourcePolicy: { policy: 'cross-origin' } }));
app.use(cors(clientCors));
app.use(express.json({ limit: '1mb' }));
app.use(cookieParser());
app.use('/uploads', express.static(path.join(__dirname, 'uploads')));
app.use('/uploads', express.static(path.join(process.cwd(), 'uploads')));
if (process.env.NODE_ENV !== 'production') app.use(morgan('dev'));
app.use('/api/', rateLimit({ windowMs: 60 * 1000, limit: 180, standardHeaders: true, legacyHeaders: false }));
app.get('/api/health', (_req, res) => res.json({ status: 'ok', app: 'TOMATO API' }));
app.use('/api/auth', authRoutes);
app.use('/api/foods', foodRoutes);
app.use('/api/orders', orderRoutes);
app.use('/api/admin', adminRoutes);
app.use('/api/coupons', couponRoutes);
app.use('/api/foods', reviewRoutes);
app.use((req, res) => res.status(404).json({ message: `Route not found: ${req.method} ${req.path}` }));
app.use((err, _req, res, _next) => {
  if (err?.type === 'entity.parse.failed') return res.status(400).json({ message: 'Request body must be valid JSON.' });
  console.error(err);
  if (err?.code === 11000) return res.status(409).json({ message: 'A record with that value already exists.' });
  if (err?.name === 'ValidationError') return res.status(400).json({ message: err.message });
  res.status(500).json({ message: process.env.NODE_ENV === 'production' ? 'Something went wrong.' : err.message });
});
export default app;
